# ============================================================
# Plot 4: XY obstacle avoidance path with printed control points
# ============================================================

plt.figure(figsize=(9, 8))
ax = plt.gca()

# Smooth Bernstein trajectory in XY
plt.plot(
    values_px,
    values_py,
    linewidth=2.0,
    label="Bernstein trajectory",
)

# XY control polygon
plt.plot(
    cp_values_px,
    cp_values_py,
    "o--",
    linewidth=1.2,
    markersize=6,
    label="Control polygon",
)

# Annotate every XY control point
for i, (x_cp, y_cp) in enumerate(zip(cp_values_px, cp_values_py)):
    ax.annotate(
        f"CP{i}\n({x_cp:.2f}, {y_cp:.2f})",
        xy=(x_cp, y_cp),
        xytext=(8, 8),
        textcoords="offset points",
        fontsize=8,
        bbox=dict(
            boxstyle="round,pad=0.2",
            fc="white",
            alpha=0.75,
        ),
        arrowprops=dict(
            arrowstyle="->",
            linewidth=0.6,
        ),
    )

# Start point from sampled trajectory
plt.scatter(
    values_px[0],
    values_py[0],
    s=120,
    marker="s",
    label="Start sampled point",
)

# Final sampled point
plt.scatter(
    values_px[-1],
    values_py[-1],
    s=140,
    marker="*",
    label="Final sampled point",
)

# First control point
plt.scatter(
    cp_values_px[0],
    cp_values_py[0],
    s=90,
    marker="x",
    linewidths=2,
    label="First control point",
)

# Last control point
plt.scatter(
    cp_values_px[-1],
    cp_values_py[-1],
    s=90,
    marker="P",
    label="Last control point",
)

# Obstacles
for idx, (ox, oy) in enumerate(OBSTACLES, start=1):
    circle = Circle(
        (ox, oy),
        OBSTACLE_RADIUS,
        fill=True,
        alpha=0.35,
        edgecolor="black",
        linewidth=1.5,
        label=f"Obstacle {idx}",
    )

    ax.add_patch(circle)

    plt.scatter(
        ox,
        oy,
        marker="x",
        s=80,
        linewidths=2,
        color="black",
    )

    ax.annotate(
        f"Obs {idx}\n({ox:.2f}, {oy:.2f})",
        xy=(ox, oy),
        xytext=(10, -20),
        textcoords="offset points",
        fontsize=8,
        bbox=dict(
            boxstyle="round,pad=0.2",
            fc="white",
            alpha=0.75,
        ),
    )

# Axis limits
all_x = (
    list(values_px)
    + list(cp_values_px)
    + [obs[0] - OBSTACLE_RADIUS for obs in OBSTACLES]
    + [obs[0] + OBSTACLE_RADIUS for obs in OBSTACLES]
)

all_y = (
    list(values_py)
    + list(cp_values_py)
    + [obs[1] - OBSTACLE_RADIUS for obs in OBSTACLES]
    + [obs[1] + OBSTACLE_RADIUS for obs in OBSTACLES]
)

margin = 0.5

plt.xlim(min(all_x) - margin, max(all_x) + margin)
plt.ylim(min(all_y) - margin, max(all_y) + margin)

