# ============================================================
# Print obstacle distance check from sampled Bernstein trajectory
# ============================================================

print("============================================================")
print("OBSTACLE DISTANCE CHECK FROM SAMPLED BERNSTEIN TRAJECTORY")
print("============================================================")

for idx, (ox, oy) in enumerate(OBSTACLES, start=1):
    distances = np.sqrt((values_px - ox) ** 2 + (values_py - oy) ** 2)
    min_distance = np.min(distances)
    min_index = np.argmin(distances)

    print(
        f"Obstacle {idx}: "
        f"center = ({ox:.6f}, {oy:.6f}), "
        f"radius = {OBSTACLE_RADIUS:.6f}, "
        f"sampled min distance = {min_distance:.9f}, "
        f"closest sample index = {min_index}, "
        f"closest point = ({values_px[min_index]:.9f}, {values_py[min_index]:.9f})"
    )

print("============================================================\n")


